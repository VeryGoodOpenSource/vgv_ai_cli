#!/bin/bash
# Prints the Homebrew formula for one vgv_ai release.
#
#   tool/generate_homebrew_formula.sh <version> <checksums-dir>
#
# <checksums-dir> holds the vgv_ai-<os>-<arch>.tar.gz.sha256 files the release
# attaches. The release_binaries workflow runs this on every release and
# commits the result to the VeryGoodOpenSource/homebrew-tap repository as
# Formula/vgv_ai.rb.
set -euo pipefail

if [ $# -ne 2 ]; then
  echo "usage: $0 <version> <checksums-dir>" >&2
  exit 64
fi

version="${1#v}"
checksums_dir="$2"
base_url="https://github.com/VeryGoodOpenSource/vgv_ai_cli/releases/download/v${version}"

sha256() {
  local file="${checksums_dir}/vgv_ai-$1.tar.gz.sha256"
  [ -f "$file" ] || { echo "missing $file" >&2; exit 1; }
  cut -d ' ' -f 1 <"$file"
}

macos_arm64="$(sha256 macos-arm64)"
macos_x64="$(sha256 macos-x64)"
linux_arm64="$(sha256 linux-arm64)"
linux_x64="$(sha256 linux-x64)"

cat <<EOF
# This file is generated by vgv_ai_cli's tool/generate_homebrew_formula.sh on
# every release. Do not edit it by hand.
class VgvAi < Formula
  desc "Configures Very Good AI coding agents and tooling"
  homepage "https://github.com/VeryGoodOpenSource/vgv_ai_cli"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base_url}/vgv_ai-macos-arm64.tar.gz"
      sha256 "${macos_arm64}"
    end
    on_intel do
      url "${base_url}/vgv_ai-macos-x64.tar.gz"
      sha256 "${macos_x64}"
    end
  end

  on_linux do
    on_arm do
      url "${base_url}/vgv_ai-linux-arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base_url}/vgv_ai-linux-x64.tar.gz"
      sha256 "${linux_x64}"
    end
  end

  def install
    bin.install "vgv_ai"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/vgv_ai --version")
  end
end
EOF
